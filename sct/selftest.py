"""Offline checks for the SCT path. No SCT, no database, no AWS.

What is being checked, in order of how much it matters:

  1. **The password never survives the run.** The scenario file holds it because
     SCT's CLI has no other way to take it; the record must not, the redaction
     must work, and the file must be deleted even when SCT fails.
  2. **Out-of-scope targets stay out of scope.** Aurora and Redshift are listed
     for the dropdown but carry no migration engine, so a selected target cannot
     leak into Phase 3 as a migration path.
  3. **Provenance is inverted from `report/export.py` and must stay that way.**
     That module's whole job is saying "not generated by AWS SCT"; this one's
     output *is* SCT's, and mixing the two claims in either direction is the
     failure mode worth a test.
  4. The parser reads SCT's CSV, sorts it, and reports what it did not
     understand rather than dropping it.
"""

